import Testing
@testable import CryptomatorCryptoLib

struct CtrCryptorTests {
	let cryptor = CryptorScheme.sivCtrMac.makeCryptor()

	let headerCiphertext: [UInt8] = [
		0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0,
		0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0, 0xF0,
		0x0D, 0x91, 0xF2, 0x9C, 0xC6, 0x35, 0xD7, 0x5E,
		0x1E, 0x42, 0x23, 0x1E, 0xC7, 0x90, 0x57, 0xE3,
		0x8D, 0x98, 0xF3, 0x58, 0x07, 0x2C, 0x9F, 0x03,
		0xBC, 0xEA, 0x5A, 0x98, 0x3B, 0x68, 0x62, 0x89,
		0x3E, 0xBC, 0x5E, 0x5E, 0x27, 0x39, 0xCB, 0x8E,
		0xD4, 0x27, 0x61, 0x06, 0x8E, 0x7F, 0x3A, 0x4E,
		0xC7, 0x9F, 0x4D, 0x3E, 0x20, 0x57, 0xDC, 0xE4,
		0x65, 0xA5, 0xFF, 0x93, 0xC2, 0x7B, 0xD2, 0xB8,
		0x3F, 0xE3, 0xD0, 0x8C, 0xB3, 0x92, 0xED, 0x96
	]

	@Test func `create header`() throws {
		let header = try cryptor.createHeader()
		#expect([UInt8](repeating: 0xF0, count: 16) == header.nonce)
		#expect([UInt8](repeating: 0xF0, count: 32) == header.contentKey)
	}

	@Test func `encrypt header`() throws {
		let header = try cryptor.createHeader()
		let encrypted = try cryptor.encryptHeader(header)
		#expect(headerCiphertext == encrypted)
	}

	@Test func `decrypt header`() throws {
		let cryptor = Cryptor(masterkey: .test, scheme: .sivCtrMac)
		let decrypted = try cryptor.decryptHeader(headerCiphertext)
		#expect([UInt8](repeating: 0xF0, count: 16) == decrypted.nonce)
		#expect([UInt8](repeating: 0xF0, count: 32) == decrypted.contentKey)
	}
}
